String modbusPanelAlarmLabel({
  required int index,
  required bool fault,
  required bool is3ku,
  required bool chinese,
}) {
  final standard = fault ? _faults : _warnings;
  final alternate = fault ? _faults3ku : _warnings3ku;
  final name = is3ku ? alternate[index] ?? standard[index] : standard[index];
  return chinese ? name.$1 : name.$2;
}
