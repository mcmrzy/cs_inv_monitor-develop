/// 根据国家名和英文省份名获取中文省份名
/// 如果找不到映射，返回原始英文名
String getLocalizedProvinceName(String countryName, String englishName) {
  final countryMap = provinceNameZhToEn[countryName];
  if (countryMap == null) return englishName;
  return countryMap[englishName] ?? englishName;
}
